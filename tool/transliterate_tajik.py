def transliterate_word(w):
    w_clean = w.lower()
    if w_clean in LEXICON:
        return LEXICON[w_clean]
    
    # Handle verbal prefixes
    if w_clean.startswith('ме') and len(w_clean) > 3:
        stem = w_clean[2:]
        if stem.startswith('-'):
            stem = stem[1:]
        if stem in LEXICON:
            return "می‌" + LEXICON[stem]
        return "می‌" + _phonetic_translit(stem)
    
    if w_clean.startswith('на') and len(w_clean) > 3:
        stem = w_clean[2:]
        if stem.startswith('-'):
            stem = stem[1:]
        if stem in LEXICON:
            return "نـ" + LEXICON[stem]
        return "نـ" + _phonetic_translit(stem)
    
    if w_clean.startswith('бе') and len(w_clean) > 3:
        stem = w_clean[2:]
        if stem.startswith('-'):
            stem = stem[1:]
        if stem in LEXICON:
            return "بی‌" + LEXICON[stem]
        return "بی‌" + _phonetic_translit(stem)
            
    # Handle suffixes
    if w_clean.endswith('ҳо') and len(w_clean) > 3:
        stem = w_clean[:-2]
        if stem in LEXICON:
            return LEXICON[stem] + "‌ها"
    if w_clean.endswith('он') and len(w_clean) > 3:
        stem = w_clean[:-2]
        if stem in LEXICON:
            return LEXICON[stem] + "ان"
    if w_clean.endswith('ӣ') and len(w_clean) > 2:
        stem = w_clean[:-1]
        if stem in LEXICON:
            base = LEXICON[stem]
            if base.endswith('ه'):
                return base[:-1] + "ه‌ای"
            return base + "ی"
    if w_clean.endswith('гӣ') and len(w_clean) > 3:
        stem = w_clean[:-2]
        if stem in LEXICON:
            return LEXICON[stem] + "گی"
    if w_clean.endswith('тар') and len(w_clean) > 4:
        stem = w_clean[:-3]
        if stem in LEXICON:
            return LEXICON[stem] + "‌تر"
    if w_clean.endswith('тарин') and len(w_clean) > 6:
        stem = w_clean[:-5]
        if stem in LEXICON:
            return LEXICON[stem] + "‌ترین"

    return _phonetic_translit(w_clean)

def _phonetic_translit(word):
    # Rule-based phonetic transliteration
    res = []
    n = len(word)
    i = 0
    while i < n:
        c = word[i]
        nxt = word[i+1] if i+1 < n else ''
        prv = word[i-1] if i > 0 else ''
        
        # Word-initial vowels
        if i == 0:
            if c == 'о':
                res.append('آ')
            elif c in ('а', 'э'):
                res.append('ا')
            elif c in ('у', 'ӯ'):
                res.append('او')
            elif c in ('и', 'ӣ'):
                res.append('ای')
            elif c == 'е':
                res.append('ای')
            elif c == 'ё':
                res.append('یا')
            elif c == 'ю':
                res.append('یو')
            elif c == 'я':
                res.append('یا')
            else:
                res.append(_map_char(c, prv, nxt, i, n))
        else:
            if c == 'о':
                res.append('ا')
            elif c == 'а':
                if i == n - 1 and prv not in ('у', 'ӯ', 'и', 'ӣ', 'о'):
                    res.append('ه')
                else:
                    pass # short vowel / implicit fatḥah in Persian
            elif c in ('у', 'ӯ'):
                res.append('و')
            elif c in ('и', 'ӣ'):
                res.append('ی')
            elif c == 'е':
                res.append('ی')
            elif c == 'ё':
                res.append('یا')
            elif c == 'ю':
                res.append('یو')
            elif c == 'я':
                res.append('یا')
            elif c == 'э':
                res.append('ا')
            else:
                res.append(_map_char(c, prv, nxt, i, n))
        i += 1
    return ''.join(res)

def _map_char(c, prv, nxt, i, n):
    char_map = {
        'б': 'ب', 'в': 'و', 'г': 'گ', 'ғ': 'غ', 'д': 'د', 'ж': 'ژ', 'з': 'ز',
        'й': 'ی', 'к': 'ک', 'қ': 'ق', 'л': 'ل', 'м': 'م', 'н': 'ن', 'п': 'پ',
        'р': 'ر', 'с': 'س', 'т': 'ت', 'ф': 'ف', 'х': 'خ', 'ҳ': 'ه', 'ч': 'چ',
        'ҷ': 'ج', 'ш': 'ش', 'ъ': 'ع', 'ь': '', 'ц': 'س', 'щ': 'ش', 'ы': 'ی', 'э': 'ا'
    }
    return char_map.get(c, c)

def transliterate_text(text):
    # Preserve formatting, newlines, and punctuation
    tokens = re.split(r'([а-яА-ЯёЁӣӯҳқҷғӢӮҲҚҶҒъЪ]+|[^\w\s]|[\s]+)', text)
    out = []
    for t in tokens:
        if not t:
            continue
        if re.match(r'^[а-яА-ЯёЁӣӯҳқҷғӢӮҲҚҶҒъЪ]+$', t):
            out.append(transliterate_word(t))
        elif t in (',', '.', '!', '?', ':', ';', '«', '»', '—', '-'):
            punct_map = {
                ',': '،',
                ';': '؛',
                '?': '؟',
                '«': '«',
                '»': '»',
                '—': '—',
                '-': '-'
            }
            out.append(punct_map.get(t, t))
        else:
            out.append(t)
    return ''.join(out)

